/* Kraken tentacle encounter — telegraph/grab/damage/escape. */
"use strict";
const assert=require("node:assert/strict");
const {KrakenGrapple}=require("../kraken-grapple.js");
const g=new KrakenGrapple();
const monster={id:"kraken-1",x:90,y:0,radius:95,phase:0};
const ship={x:0,y:0,vx:0,vy:0,hull:100};
let splashes=0;
const ocean={splash(){splashes++;}};
const simulate=n=>{for(let i=0;i<n;i++)g.update(monster,1/60,ship,ocean);};
let st=g.get(monster);
assert.equal(st.arms.length,8,"One coordinator owns eight arm states");
assert.equal(st.phase,"idle");
simulate(1);
assert.equal(st.phase,"warn","Kraken must telegraph before a grab");
assert(g.lastEvent.message.includes("Bubbles"));
assert.equal(ship.hull,100,"No invisible pre-warning damage");
simulate(76);
assert.equal(st.phase,"reach","Warning must precede reach");
assert.equal(ship.hull,100);
simulate(65);
assert.equal(st.phase,"grab","Reach turns into short grappling state");
assert(g.isGrabbing(monster.id));
simulate(100);
assert(ship.hull<100,"Holding tentacle applies bounded hull damage");
assert(Math.hypot(ship.vx,ship.vy)<30,"Tentacle pulls as gentle acceleration, not teleport");
assert(g.hit(monster.id),"Aiming at grabbing arm can deal damage");
assert.equal(st.health,1);
assert(g.hit(monster.id));
assert.equal(st.phase,"recoil","Two hits free the ship");
assert(!g.isGrabbing(monster.id));
assert.equal(g.hit(monster.id),false,"Recoil arm cannot be farmed for repeated hits");
simulate(50);
assert.equal(st.phase,"cooldown");
simulate(220);
assert(["cooldown","warn","idle"].includes(st.phase));
assert(splashes>0,"Kraken must visibly disturb the water");
const noPlayer={x:10000,y:10000,vx:0,vy:0,hull:100};
const distant={id:"kraken-remote",x:0,y:0,radius:90,phase:0};
simulate(1);
for(let i=0;i<120;i++)g.update(distant,1/60,noPlayer,ocean);
assert.equal(g.get(distant).phase,"idle","Kraken stays passive when the player is far away");
const ctx={save(){},restore(){},beginPath(){},moveTo(){},quadraticCurveTo(){},stroke(){},arc(){},lineTo(){}};
assert.doesNotThrow(()=>g.draw(ctx,(x,y)=>({x,y}),monster,ship));
console.log("PASS: eight arm states, telegraph, reversible grab, no snap, damage, two-hit release and distance activation.");
