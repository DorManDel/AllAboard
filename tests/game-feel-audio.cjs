/* V0.7 automated contracts: wave-driven pose, trim, sound catalog, prefab advisory. */
"use strict";
const assert=require("node:assert/strict");
const {FeelEngine,wavePose,trimEfficiency}=require("../game-feel.js");
const {AudioLab,moods,sounds,midiHz}=require("../audio-lab.js");
const {auditUnityText,handoff}=require("../unity-readiness.js");
const {plans}=require("../mechanic-catalog.js");
const Ocean=require("../ocean.js");
const Vessel=require("../vessel.js");
const wave=new Ocean(),ship={x:30,y:20,heading:60,vx:0,vy:0};
const settings={waveHeight:1,windDirection:0,windStrength:3,waveDetail:22};
const pose=wavePose(wave,ship,settings,0);
assert(Number.isFinite(pose.bob)&&Number.isFinite(pose.pitch)&&Number.isFinite(pose.roll));
const rotated=wavePose(wave,{...ship,heading:200},settings,0);
assert.notDeepEqual(rotated,pose,"Wave pose must depend on ship angle");
assert(pose.roll<=.06&&pose.roll>=-.06,"Wave roll must be clamped");
const engine=new FeelEngine();
engine.fire(1);assert(engine.recoil>0);
engine.hit(.7);assert(engine.impact>0);
engine.step(1/60);
const shot=engine.pose(wave,ship,settings);
assert(Math.abs(shot.shakeX)+Math.abs(shot.shakeY)>0);
engine.reducedMotion=true;
const reduced=engine.pose(wave,ship,settings);
assert.equal(reduced.shakeX,0);assert.equal(reduced.shakeY,0);
for(let i=0;i<300;i++)engine.step(1/60);
assert(engine.recoil<.001,"Recoil must decay without permanent ship displacement");
const trim=trimEfficiency(0,90,0,false);
assert(trim.angle>0,"Auto trim selects desired sail angle");
const manual=trimEfficiency(0,90,-45,true);
assert(manual.bonus<trim.bonus,"Bad manual trim is weaker than automatic");
assert(manual.bonus>=.15,"Even badly trimmed sails retain minimum arcade propulsion");
const shipState={x:0,y:0,vx:0,vy:0,heading:0,angularVelocity:0};
const anchor={down:false,phase:"raised",point:{x:0,y:0}};
const vesselSettings={
  sail:100,windStrength:3,windDirection:90,baseThrust:0,windDrive:1,
  steerSensitivity:1,waterDrag:1,lateralDrag:5.5,yawResponse:3,
  sailAutoTrim:false,sailTrim:-45};
Vessel.step(shipState,anchor,{rudder:0},vesselSettings,{x:0,y:0},1/60);
assert.equal(shipState.sailTrim,-45);
assert(shipState.trimFactor<1,"Manual trim affects actual vessel physics");
vesselSettings.sailAutoTrim=true;
Vessel.step(shipState,anchor,{rudder:0},vesselSettings,{x:0,y:0},1/60);
assert.equal(shipState.trimFactor,1);
const ids=sounds.map(s=>s.id);
assert.equal(new Set(ids).size,ids.length,"SFX event ids must be unique");
assert.equal(sounds.length,15);assert.equal(moods.length,7);
assert(moods.every(m=>m.notes.length===8&&m.bpm>=60&&m.bpm<150));
assert(Math.abs(midiHz(440,12)-880)<.001);
const audio=new AudioLab();
assert.equal(audio.muted,true,"No autoplay before user gesture");
assert.equal(audio.event("shot"),true);
assert.equal(audio.eventLog.length,1);
assert.equal(audio.playing,false);
assert.equal(audio.setMood("kraken"),true);
assert.equal(audio.setMood("non-existent"),false);
assert.equal(audio.musicId,"kraken");
const yaml="%YAML 1.1\n--- !u!1 &1\nGameObject:\n  m_Name: Boat\n--- !u!114 &2\nMonoBehaviour:\n  m_Script: {fileID: 0}\n";
const report=auditUnityText(yaml,"boat.prefab");
assert.equal(report.gameObjects,1);assert.equal(report.monoBehaviours,1);
assert(report.issues.some(x=>x.severity==="error"),"Missing script should be detected");
const clean=auditUnityText("%YAML 1.1\n--- !u!1 &1\nGameObject:\n  m_Name: Ship\n","ship.prefab");
assert.equal(clean.issues.length,0);
const plan=plans.find(p=>p.id==="sailing-feel");
assert(plan);
const contract=handoff(plan);
assert(contract.includes("Unity/Codex prompt"));
assert(contract.includes("PlayMode"));
assert(contract.includes("CHANGELOG.md"));
console.log("PASS: wave-driven pose, recoil/reduced motion, trim physics, 7 moods, 15 SFX, prefab YAML warning and Unity handoff.");
