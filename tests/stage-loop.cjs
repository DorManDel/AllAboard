/* Stage + endless risk loop contract tests. Run node tests/stage-loop.cjs */
"use strict";
const assert=require("node:assert/strict");
const {StageSession,hints}=require("../stage-loop.js");
const run=new StageSession();
assert.equal(run.state.stage,1);
assert.equal(run.state.phase,"objective");
assert.equal(hints[0].start,0);
assert.equal(hints[hints.length-1].end,10);
assert(hints.every((h,i)=>i===0||h.start===hints[i-1].end),"Tutorial hints must cover 10 seconds without gaps");
assert.equal(run.completeObjective(),true);
assert.equal(run.state.phase,"choice");
assert.equal(run.state.bankedCoins,50,"Completing objective guarantees its reward");
assert.equal(run.completeObjective(),false,"Objective reward cannot be farmed repeatedly");
assert.equal(run.stay(),true);
const d1=run.difficulty;
const b1=run.potentialBonus;
assert(run.tick(10));
assert(run.difficulty>d1,"Staying at sea must increase danger");
assert(run.potentialBonus>b1,"Longer risk should improve potential loot");
assert(run.survive());
assert.equal(run.state.phase,"choice");
assert(run.state.pendingCoins>0,"Risk round earns unbanked optional loot");
const pending=run.state.pendingCoins;
assert(run.stay());
assert(run.difficulty>d1,"Later optional risk rounds should be more difficult");
assert(run.fail());
assert.equal(run.state.pendingCoins,0,"Defeat drops unbanked bonus");
assert.equal(run.state.bankedCoins,50,"Defeat cannot erase banked base stage reward");
assert.equal(run.state.stage,1,"Defeat doesn't reset the stage");
assert.equal(run.state.phase,"port");
assert(run.resume());
assert.equal(run.state.phase,"choice","Completed objective remains completed when returning");
assert.equal(run.completeObjective(),false,"Resuming cannot double-award objective");
assert(run.stay());
assert(run.survive());
const newBonus=run.state.pendingCoins;
assert(newBonus>0);
assert(run.cashOut());
assert.equal(run.state.phase,"port");
assert.equal(run.state.bankedCoins,50+newBonus,"Cash out banks the optional reward");
assert.equal(run.state.stage,1,"Leaving remains on same stage checkpoint");
const saved=run.snapshot();
const loaded=new StageSession(saved);
assert.equal(loaded.state.phase,"port");
assert.equal(loaded.state.stage,run.state.stage);
assert.equal(loaded.state.bankedCoins,run.state.bankedCoins);
assert(loaded.nextStage());
assert.equal(loaded.state.stage,2);
assert.equal(loaded.state.phase,"objective");
assert.equal(loaded.state.objectiveCleared,false);
assert.equal(loaded.state.pendingCoins,0);
assert(loaded.completeObjective());
assert(loaded.state.bankedCoins>run.state.bankedCoins);
const risky=new StageSession();
risky.completeObjective();risky.stay();risky.tick(15);risky.survive();risky.stay();
const restore=new StageSession(risky.snapshot());
assert.equal(restore.state.phase,"port","Never resume mid-hazard after browser reload");
assert.equal(restore.state.pendingCoins,0,"Unbanked hazard bonuses do not carry into port");
assert.equal(restore.state.objectiveCleared,true);
assert.equal(restore.state.bankedCoins,risky.state.bankedCoins);
assert(run.resume(),"Can return to a finished stage after cashout");
assert.equal(run.nextStage(),false,"Cannot skip a stage while still sailing");
assert.equal(run.tick(-4),false);
assert.equal(run.tick(10),false);
console.log("PASS: 10s tutorial timeline, objective guarantee, escalating risk, bank/cashout/fail, same-stage resume and stage advancement.");
